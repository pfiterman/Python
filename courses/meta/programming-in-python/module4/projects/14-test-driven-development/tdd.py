# Test-driven development
# Write the tests first, and then the code, so that the tests will pass.

# Standard steps - red/green refactor cycle
# 1. Write a test for a feature that fails
# 2. Write code in accordance with the tests
# 3. Run the tests expecting them to fail
# 4. Evaluate the error and refactor the code as needed
# 5. Rerun the process

# Red - failed tests
# Green - passing tests

# Advantages of TDD
# 1. Writing tests first ensures the tests cover the code
# 2. Forecasting
# 3. Integrating components
# 4. Ease to refactor

