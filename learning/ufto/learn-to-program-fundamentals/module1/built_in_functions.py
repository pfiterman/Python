# max is one of the Python built-in functions
print(f"max(36.7, 23.4) = {max(36.7, 23.4)}")
print(f"max(8.34, 8.25, 8.35, 8.42) = {max(8.34, 8.25, 8.35, 8.42)}")
print(f"max(8, 30, 50) = {max(8, 30, 50)}")
print(f"max(453.34, 500) = {max(453.34, 500)}")

